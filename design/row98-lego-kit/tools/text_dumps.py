"""List live text-dump cells: one inline run of text holding a 3+ item list.

Heuristic only (owner rule 2026-10-19): a candidate is the innermost visible
element with >= 150 characters and >= 2 list separators (`;` or `·`), outside
see-also and cite chips. Each candidate is an *opportunity* to go one layer
deeper (LEGO-LOGIC snap rule 9), not a defect list. Writes ../TEXT-DUMPS.md.
"""
import glob
import os

from playwright.sync_api import sync_playwright

BASE = os.environ.get("MAP_BASE", "http://localhost:8765/")
CHROME = os.environ.get("CHROME", "/usr/local/bin/google-chrome")
KIT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ROOT = os.path.abspath(os.path.join(KIT, "..", ".."))

JS = r"""() => {
  const hit = e => {
    if (e.closest('.cite-run, nav, .see, .m-see, .see-also-strip')) return null;
    if ([...e.querySelectorAll('*')].some(d => !getComputedStyle(d).display.startsWith('inline'))) return null;
    const r = e.getBoundingClientRect(); if (!r.width) return null;
    const t = e.textContent.replace(/\s+/g, ' ').trim();
    const seps = (t.match(/;|·/g) || []).length;
    return t.length >= 150 && seps >= 2 ? {t, seps} : null;
  };
  const all = [...document.querySelectorAll('p, li, span, div')].filter(e => hit(e));
  const inner = all.filter(e => !all.some(o => o !== e && e.contains(o)));
  return inner.map(e => {
    const h = hit(e); const sec = e.closest('[aria-label]');
    return {cls: e.tagName.toLowerCase() + (e.className ? '.' + String(e.className).trim().split(/\s+/).join('.') : ''),
            sec: sec ? sec.getAttribute('aria-label') : '', seps: h.seps, t: h.t};
  });
}"""


def main():
    files = sorted(glob.glob(os.path.join(ROOT, "*/draft-v1-linked/visuals/*.html")))
    files += [os.path.join(ROOT, p, "draft-v1-linked/index.html") for p in ("cf-2018", "ifrs-18")]
    rows = []
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path=CHROME, args=["--no-sandbox"])
        pg = b.new_context(viewport={"width": 1280, "height": 900}, color_scheme="dark").new_page()
        for f in files:
            rel = os.path.relpath(f, ROOT)
            pg.goto(BASE + rel, wait_until="networkidle")
            for r in pg.evaluate(JS):
                rows.append((rel, r))
        b.close()
    out = ["# Text-dump cells — opportunities to go one layer deeper", "",
           "Generated by `tools/text_dumps.py` from the live maps (dark, 1280). A row = the innermost visible element "
           "whose descendants are all inline (one run of text, not an existing grid), with ≥ 150 characters and ≥ 2 list separators (`;` or `·`), excluding see-also and cite chips. "
           "Heuristic, not a defect list: each row is a candidate for `LEGO-LOGIC.md` snap rule 9. "
           "Masters repeat chapter text through the splice, so some rows appear twice.", "",
           f"**{len(rows)} candidates on {len({r[0] for r in rows})} maps.**", "",
           "| map | element | section (`aria-label`) | separators | text (first 160 characters) |", "|---|---|---|---|---|"]
    for rel, r in rows:
        t = r["t"][:160] + ("…" if len(r["t"]) > 160 else "")
        out.append(f"| {rel.replace('/draft-v1-linked/visuals/', ' ').replace('/draft-v1-linked/', ' ')} | `{r['cls']}` | "
                   f"{r['sec'][:70]} | {r['seps']} | {t.replace('|', '‖')} |")
    with open(os.path.join(KIT, "TEXT-DUMPS.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(len(rows), "candidates")


if __name__ == "__main__":
    main()
